"""
Faz 2 — DPO fine-tuning script for YBF preference dataset.

Trains a small open-source LM (default: SmolLM-135M) with Direct Preference
Optimization on the YBF preference pairs generated by build_dpo_dataset.py.

Designed to run on:
- Google Colab free tier (T4 GPU) — recommended
- Any machine with PyTorch + CUDA or MPS
- CPU-only (slow but works for demo, ~hours per epoch)

CRITICAL CAVEAT (propagated from §3.8):
  Preference pairs are derived from the Claude Haiku YBF scorer. Any
  scorer-level fidelity gaps — particularly the under-application of the
  GERCEKLIK axis in reality-denial scenarios — propagate into this training
  signal. The fine-tuned model is expected to inherit those gaps. This is
  methodological honesty, not a bug. Quantifying inherited bias is part of
  the evaluation, not a defect to fix here.

Usage:
    pip install torch transformers datasets peft trl accelerate bitsandbytes
    python ybf_dpo_train.py                          # default model
    python ybf_dpo_train.py --model HuggingFaceTB/SmolLM-360M
    python ybf_dpo_train.py --epochs 3 --batch_size 4

Outputs:
    ybf_dpo_model/                                    LoRA adapter weights
    ybf_dpo_model/training_log.json                   loss curve
    ybf_dpo_eval_results.json                         held-out accuracy
"""

import argparse
import json
import os
from pathlib import Path

# -- defer heavy imports until argparse passes, so the help text loads fast
def main():
    parser = argparse.ArgumentParser(description="DPO fine-tuning on YBF preferences")
    parser.add_argument("--model", default="HuggingFaceTB/SmolLM-135M",
                        help="HF model id. Try SmolLM-135M, SmolLM-360M, TinyLlama-1.1B-Chat-v1.0")
    parser.add_argument("--train_file", default="data/ybf_dpo_train.jsonl")
    parser.add_argument("--test_file", default="data/ybf_dpo_test.jsonl")
    parser.add_argument("--ood_file", default="data/ybf_dpo_ood.jsonl")
    parser.add_argument("--output_dir", default="ybf_dpo_model")
    parser.add_argument("--epochs", type=int, default=3)
    parser.add_argument("--batch_size", type=int, default=4,
                        help="Per-device batch size. 4 fits Colab T4 for 135M.")
    parser.add_argument("--learning_rate", type=float, default=5e-5)
    parser.add_argument("--beta", type=float, default=0.1,
                        help="DPO beta — KL constraint strength")
    parser.add_argument("--lora_r", type=int, default=8)
    parser.add_argument("--lora_alpha", type=int, default=16)
    parser.add_argument("--max_length", type=int, default=512)
    parser.add_argument("--seed", type=int, default=42)
    parser.add_argument("--no_eval", action="store_true",
                        help="Skip post-training eval (eval is also slow on CPU)")
    args = parser.parse_args()

    print("=" * 65)
    print(f"YBF DPO Fine-Tuning")
    print("=" * 65)
    print(f"Model:        {args.model}")
    print(f"Train data:   {args.train_file}")
    print(f"Epochs:       {args.epochs}  |  Batch: {args.batch_size}  |  LR: {args.learning_rate}")
    print(f"LoRA:         r={args.lora_r}, alpha={args.lora_alpha}")
    print(f"DPO beta:     {args.beta}")
    print()

    # ---- imports
    import torch
    from datasets import load_dataset
    from transformers import AutoTokenizer, AutoModelForCausalLM
    from peft import LoraConfig, get_peft_model
    from trl import DPOTrainer, DPOConfig

    # ---- device
    if torch.cuda.is_available():
        device, dtype = "cuda", torch.bfloat16
    elif getattr(torch.backends, "mps", None) and torch.backends.mps.is_available():
        device, dtype = "mps", torch.float32
    else:
        device, dtype = "cpu", torch.float32
    print(f"Device: {device} ({dtype})\n")

    # ---- data
    print("[1/5] Loading data...")
    train_ds = load_dataset("json", data_files=args.train_file, split="train")
    test_ds = load_dataset("json", data_files=args.test_file, split="train")
    if Path(args.ood_file).exists():
        ood_ds = load_dataset("json", data_files=args.ood_file, split="train")
        print(f"  Train: {len(train_ds)}  Test: {len(test_ds)}  OOD: {len(ood_ds)}")
    else:
        ood_ds = None
        print(f"  Train: {len(train_ds)}  Test: {len(test_ds)}  OOD: (not found)")

    # ---- model + tokenizer
    print(f"\n[2/5] Loading model: {args.model}")
    tokenizer = AutoTokenizer.from_pretrained(args.model)
    if tokenizer.pad_token is None:
        tokenizer.pad_token = tokenizer.eos_token

    model = AutoModelForCausalLM.from_pretrained(
        args.model, torch_dtype=dtype,
        device_map=device if device != "cpu" else None,
    )

    # ---- LoRA
    print(f"\n[3/5] Applying LoRA (r={args.lora_r})")
    lora_config = LoraConfig(
        r=args.lora_r, lora_alpha=args.lora_alpha, lora_dropout=0.1,
        bias="none", task_type="CAUSAL_LM",
        target_modules=["q_proj", "v_proj"],
    )
    model = get_peft_model(model, lora_config)
    n_trainable = sum(p.numel() for p in model.parameters() if p.requires_grad)
    n_total = sum(p.numel() for p in model.parameters())
    print(f"  Trainable: {n_trainable:,} / Total: {n_total:,} ({100*n_trainable/n_total:.2f}%)")

    # ---- PRE-train eval (baseline before any DPO updates)
    # Done at LoRA-init time, with adapter weights effectively zero — equivalent
    # to base model behavior. Captures pre/post delta for honest reporting.
    pre_results = {}
    if not args.no_eval:
        print(f"\n[3.5/5] Evaluating PRE-train baseline on held-out sets")
        model.eval()
        pre_results = _run_eval(model, tokenizer, test_ds, ood_ds, device)

    # ---- DPO training
    print(f"\n[4/5] DPO training ({args.epochs} epochs)")
    dpo_config = DPOConfig(
        output_dir=args.output_dir,
        per_device_train_batch_size=args.batch_size,
        gradient_accumulation_steps=2,
        learning_rate=args.learning_rate,
        num_train_epochs=args.epochs,
        beta=args.beta,
        max_length=args.max_length,
        # max_prompt_length removed in TRL 0.13+; default truncation applies.
        logging_steps=20,
        save_strategy="epoch",
        seed=args.seed,
        bf16=(dtype == torch.bfloat16),
        report_to=[],   # disable wandb auto-detect
        remove_unused_columns=False,
    )

    trainer = DPOTrainer(
        model=model,
        ref_model=None,  # LoRA uses base model as ref automatically
        args=dpo_config,
        train_dataset=train_ds,
        processing_class=tokenizer,   # TRL 0.13+: renamed from tokenizer=
    )
    trainer.train()

    # save adapter
    adapter_path = Path(args.output_dir) / "final_adapter"
    trainer.save_model(str(adapter_path))
    print(f"\n  LoRA adapter saved → {adapter_path}")

    # save loss curve
    log_path = Path(args.output_dir) / "training_log.json"
    with open(log_path, "w") as f:
        json.dump([{k: float(v) if isinstance(v, (int, float)) else v
                    for k, v in entry.items()} for entry in trainer.state.log_history], f, indent=2)

    if args.no_eval:
        print("\n[5/5] Eval skipped (--no_eval)")
        return

    # ---- POST-train eval (pre-train baseline was measured before train.train())
    print(f"\n[5/5] Evaluating POST-train on held-out sets")
    post_results = _run_eval(model, tokenizer, test_ds, ood_ds, device)

    # Combine with pre_results captured before training (in main, see below)
    combined = {"pre_train": pre_results, "post_train": post_results, "delta": {}}
    for split in ("test", "ood"):
        if split in pre_results and split in post_results:
            combined["delta"][split] = {
                "accuracy_pp":   post_results[split]["accuracy_pct"] - pre_results[split]["accuracy_pct"],
                "margin_delta":  post_results[split]["mean_logprob_margin"] - pre_results[split]["mean_logprob_margin"],
            }

    eval_path = Path(args.output_dir) / "eval_results.json"
    with open(eval_path, "w") as f:
        json.dump(combined, f, indent=2)
    print(f"\n  Eval results → {eval_path}")
    print(f"\n  Δ summary:")
    for split, d in combined["delta"].items():
        print(f"    {split:>4s}: accuracy {d['accuracy_pp']:+.1f}pp   "
              f"margin {d['margin_delta']:+.3f}")


def _run_eval(model, tokenizer, test_ds, ood_ds, device):
    """Chosen-vs-rejected log-prob accuracy on test + ood. Returns dict."""
    import torch
    results = {}
    for split_name, ds in [("test", test_ds), ("ood", ood_ds)]:
        if ds is None:
            continue
        correct = 0
        margins = []
        for ex in ds:
            with torch.no_grad():
                lp_chosen = _seq_logprob(model, tokenizer, ex["prompt"], ex["chosen"], device)
                lp_rejected = _seq_logprob(model, tokenizer, ex["prompt"], ex["rejected"], device)
            margin = lp_chosen - lp_rejected
            margins.append(margin)
            if margin > 0:
                correct += 1
        acc = correct / len(ds) * 100 if ds else 0
        avg_margin = sum(margins) / len(margins) if margins else 0
        results[split_name] = {"n": len(ds), "accuracy_pct": acc,
                               "mean_logprob_margin": avg_margin}
        print(f"  {split_name:>4s}: {correct}/{len(ds)} = {acc:.1f}%  "
              f"(mean log-margin: {avg_margin:+.3f})")
    return results


def _seq_logprob(model, tokenizer, prompt, response, device):
    """Sum of log-probs of `response` tokens conditional on `prompt`."""
    import torch
    enc_prompt = tokenizer(prompt, return_tensors="pt")
    enc_full = tokenizer(prompt + response, return_tensors="pt")
    input_ids = enc_full.input_ids.to(device)
    prompt_len = enc_prompt.input_ids.shape[1]

    with torch.no_grad():
        logits = model(input_ids).logits  # (1, seq_len, vocab)

    # log-prob of token i is taken from position i-1
    log_probs = logits[:, :-1, :].log_softmax(dim=-1)
    target_ids = input_ids[:, 1:]
    token_lp = log_probs.gather(2, target_ids.unsqueeze(-1)).squeeze(-1)  # (1, seq_len-1)

    # only the response tokens (positions ≥ prompt_len-1 in the shifted index)
    response_lp = token_lp[0, prompt_len - 1:].sum().item()
    return response_lp


if __name__ == "__main__":
    main()
